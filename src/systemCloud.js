async function invokeSystemApi(action, payload = {}, options = {}) {
  const {
    data,
    error,
  } = await withCloudTimeout(
    supabase.functions.invoke(
      "system-api",
      {
        body: {
          action,
          payload,
          ...(options.idempotencyKey
            ? {
                idempotency_key:
                  options.idempotencyKey,
              }
            : {}),
        },
        headers:
          options.idempotencyKey
            ? {
                "x-idempotency-key":
                  options.idempotencyKey,
              }
            : undefined,
      }
    ),
    Number(options.timeoutMs) || SYSTEM_API_TIMEOUT_MS,
    "SYSTEM_API_TIMEOUT"
  );

  if (error) {
    throw error;
  }

  if (data?.error) {
    const failure =
      new Error(
        data.error
      );

    failure.code =
      data.code ||
      "SYSTEM_API_ERROR";

    throw failure;
  }

  return data;
}

