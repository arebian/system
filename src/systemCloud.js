async function evaluateAchievements(
  profile,
  userId
) {
  const {
    data:
      catalog,
    error:
      catalogError,
  } =
    await supabase
      .from(
        "achievements"
      )
      .select("*")
      .eq(
        "active",
        true
      );

  if (catalogError) {
    throw catalogError;
  }

  const completedBosses =
    (
      profile.bossQuests ||
      []
    ).filter(
      (boss) =>
        boss.status ===
        "COMPLETE"
    );

  const masteredCount =
    Object.values(
      profile.masteredSkills ||
      {}
    ).filter(Boolean)
      .length;

  const completedGoals =
    (
      profile.goals ||
      []
    ).filter(
      (goal) =>
        goal.status ===
        "COMPLETE"
    ).length;

  const proofCount =
    (
      profile.proofs ||
      []
    ).length;

  const rules = {
    "first-blood":
      (
        profile.questLog ||
        []
      ).length >= 1,

    "seven-day-streak":
      Number(
        profile.streak ||
          0
      ) >= 7,

    "c-rank-slayer":
      completedBosses.some(
        (boss) =>
          boss.rank ===
          "C"
      ),

    "s-rank-slayer":
      completedBosses.some(
        (boss) =>
          boss.rank ===
          "S"
      ),

    "skill-master":
      masteredCount >= 1,

    "tenfold-mastery":
      masteredCount >= 10,

    "first-5k":
      Number(
        profile.totalDistance ||
          0
      ) >= 5,

    "first-10k":
      Number(
        profile.totalDistance ||
          0
      ) >= 10,

    "wealth-keeper":
      (
        profile.wealthLogs ||
        []
      ).length >= 1,

    "objective-cleared":
      completedGoals >= 1,

    "proof-of-work":
      proofCount >= 1,

    "ascended":
      Number(
        profile.level ||
          1
      ) >= 101,
  };

  const unlockedRows =
    (
      catalog ||
      []
    )
      .filter(
        (achievement) =>
          Boolean(
            rules[
              achievement.slug
            ]
          )
      )
      .map(
        (achievement) => ({
          user_id:
            userId,
          achievement_id:
            achievement.id,
          progress:
            1,
          target:
            1,
          unlocked:
            true,
          unlocked_at:
            new Date().toISOString(),
          metadata: {},
        })
      );

  if (
    unlockedRows.length
  ) {
    const {
      error,
    } =
      await supabase
        .from(
          "user_achievements"
        )
        .upsert(
          unlockedRows,
          {
            onConflict:
              "user_id,achievement_id",
          }
        );

    if (error) {
      console.error(
        "ACHIEVEMENT SYNC FAILED:",
        error
      );
    }
  }

  return (
    catalog ||
    []
  );
}

async function syncAdaptiveDimensions(
  userId,
  dimensions
) {
  const rows = dimensions.map(
    (item, index) => ({
      user_id: userId,
      category: item.category,
      current_score: item.score,
      target_score: 70,
      priority_weight: index === 0 ? 2 : 1,
      assigned_count: 0,
      accepted_count: 0,
      completed_count: 0,
      failed_count: 0,
      ignored_count: 0,
      neglect_count: item.score < 50 ? 1 : 0,
      metadata: {
        reason: item.reason,
      },
      updated_at: new Date().toISOString(),
    })
  );

  const results = await Promise.allSettled(
    rows.map(async (row) => {
      const {
        data: existing,
        error: lookupError,
      } = await supabase
        .from(
          "adaptive_dimensions"
        )
        .select(
          "id,neglect_count"
        )
        .eq(
          "user_id",
          userId
        )
        .eq(
          "category",
          row.category
        )
        .maybeSingle();

      if (lookupError) {
        throw lookupError;
      }

      if (existing) {
        const {
          error: updateError,
        } = await supabase
          .from(
            "adaptive_dimensions"
          )
          .update({
            current_score: row.current_score,
            target_score: row.target_score,
            priority_weight: row.priority_weight,
            neglect_count: Math.max(
              Number(
                existing.neglect_count ||
                  0
              ),
              row.neglect_count
            ),
            metadata: row.metadata,
            updated_at: row.updated_at,
          })
          .eq(
            "id",
            existing.id
          );

        if (updateError) {
          throw updateError;
        }

        return;
      }

      const {
        error: insertError,
      } = await supabase
        .from(
          "adaptive_dimensions"
        )
        .insert(row);

      if (insertError) {
        throw insertError;
      }
    })
  );

  const failed = results.find(
    (result) =>
      result.status ===
      "rejected"
  );

  if (failed) {
    console.warn(
      "ADAPTIVE DIMENSION SYNC DEFERRED:",
      failed.reason
    );
  }
}

async function resolveAdaptiveFallback(
  profile,
  categoryOrder
) {
  const {
    data: candidates,
    error,
  } = await withCloudTimeout(
    supabase
      .from(
        "quest_library"
      )
      .select("*")
      .eq(
        "active",
        true
      )
      .eq(
        "quest_type",
        "STANDARD"
      )
      .in(
        "category",
        categoryOrder
      )
      .order(
        "health_value",
        {
          ascending: false,
        }
      )
      .limit(40),
    SYSTEM_API_TIMEOUT_MS,
    "ADAPTIVE_CATALOG_TIMEOUT"
  );

  if (error) {
    throw error;
  }

  const freshCandidates =
    withoutRecentAdaptiveCandidates(
      candidates || [],
      profile,
      Date.now(),
      7,
    );

  return (
    chooseAdaptiveFallbackCandidate(
      freshCandidates,
      profile,
      categoryOrder
    ) ||
    chooseAdaptiveFallbackCandidate(
      candidates || [],
      profile,
      categoryOrder
    )
  );
}

