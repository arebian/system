const MAX_PROOF_UPLOAD_BYTES =
  35 * 1024 * 1024;

export async function uploadProofFile(
  file
) {
  if (!file) {
    throw new Error(
      "PROOF_FILE_REQUIRED"
    );
  }

  if (
    Number(file.size || 0) >
    MAX_PROOF_UPLOAD_BYTES
  ) {
    throw new Error(
      "PROOF_FILE_TOO_LARGE_MAX_35_MB"
    );
  }

  const user =
    await currentUser();

  if (!user) {
    throw new Error(
      "AUTH REQUIRED"
    );
  }

  const extension =
    String(
      file.name ||
        "proof.jpg"
    )
      .split(".")
      .pop()
      .replace(
        /[^a-zA-Z0-9]/g,
        ""
      )
      .toLowerCase() ||
    "jpg";

  const path =
    `${user.id}/${Date.now()}-${Math.random()
      .toString(36)
      .slice(2, 10)}.${extension}`;

  const {
    error:
      uploadError,
  } =
    await withCloudTimeout(
      supabase.storage
        .from("proofs")
        .upload(
          path,
          file,
          {
            cacheControl:
              "3600",
            upsert: false,
            contentType:
              file.type ||
              undefined,
          }
        ),
      20000,
      "PROOF_UPLOAD_TIMEOUT"
    );

  if (uploadError) {
    throw uploadError;
  }

  const {
    data:
      signed,
    error:
      signedError,
  } =
    await withCloudTimeout(
      supabase.storage
        .from("proofs")
        .createSignedUrl(
          path,
          60 * 60
        ),
      SYSTEM_API_TIMEOUT_MS,
      "PROOF_URL_TIMEOUT"
    );

  if (signedError) {
    return {
      path,
      url: "",
    };
  }

  return {
    path,
    url:
      signed?.signedUrl ||
      "",
  };
}

