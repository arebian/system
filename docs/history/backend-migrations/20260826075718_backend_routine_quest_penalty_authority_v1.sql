create table if not exists public.quest_penalty_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  user_quest_id uuid not null references public.user_quests(id) on delete cascade,
  xp_penalty integer not null default 0 check (xp_penalty >= 0),
  reason text not null default 'QUEST_EXPIRED',
  metadata jsonb not null default '{}'::jsonb,
  applied_at timestamptz not null default now(),
  unique(user_quest_id)
);
create index if not exists quest_penalty_events_user_time_idx on public.quest_penalty_events(user_id, applied_at desc);
alter table public.quest_penalty_events enable row level security;
drop policy if exists quest_penalty_events_select_own on public.quest_penalty_events;
create policy quest_penalty_events_select_own on public.quest_penalty_events for select to authenticated using (user_id = (select auth.uid()));

create table if not exists public.routine_checkins (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  checkin_type text not null check (checkin_type in ('SLEEP','WAKE')),
  occurred_at timestamptz not null,
  expected_local_time time,
  timezone text not null default 'UTC',
  status text not null check (status in ('ON_TIME','LATE','EARLY','UNVERIFIED')),
  delta_minutes integer,
  source text not null default 'CLIENT',
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists routine_checkins_user_time_idx on public.routine_checkins(user_id, occurred_at desc);
alter table public.routine_checkins enable row level security;
drop policy if exists routine_checkins_select_own on public.routine_checkins;
create policy routine_checkins_select_own on public.routine_checkins for select to authenticated using (user_id = (select auth.uid()));

create or replace function public.system_update_routine(
  p_shift_mode text,
  p_sleep_time time,
  p_wake_time time,
  p_timezone text default 'UTC',
  p_verification_minutes integer default 10,
  p_metadata jsonb default '{}'::jsonb
) returns jsonb language plpgsql security definer set search_path=public as $$
declare v_user uuid := auth.uid(); v_row public.player_routines;
begin
  if v_user is null then raise exception 'AUTH_REQUIRED'; end if;
  if p_verification_minutes < 1 or p_verification_minutes > 120 then raise exception 'INVALID_VERIFICATION_WINDOW'; end if;
  insert into public.player_routines(user_id,shift_mode,sleep_time,wake_time,verification_minutes,timezone,metadata)
  values(v_user,upper(coalesce(p_shift_mode,'STANDARD')),p_sleep_time,p_wake_time,p_verification_minutes,coalesce(nullif(p_timezone,''),'UTC'),coalesce(p_metadata,'{}'::jsonb))
  on conflict(user_id) do update set shift_mode=excluded.shift_mode,sleep_time=excluded.sleep_time,wake_time=excluded.wake_time,verification_minutes=excluded.verification_minutes,timezone=excluded.timezone,metadata=public.player_routines.metadata||excluded.metadata,updated_at=now()
  returning * into v_row;
  return to_jsonb(v_row);
end $$;

create or replace function public.system_routine_checkin(p_type text,p_occurred_at timestamptz default now(),p_metadata jsonb default '{}'::jsonb)
returns jsonb language plpgsql security definer set search_path=public as $$
declare v_user uuid:=auth.uid(); v_r public.player_routines; v_expected time; v_local timestamp; v_delta integer; v_status text; v_id bigint;
begin
 if v_user is null then raise exception 'AUTH_REQUIRED'; end if;
 select * into v_r from public.player_routines where user_id=v_user;
 if not found then raise exception 'ROUTINE_NOT_CONFIGURED'; end if;
 if upper(p_type)='SLEEP' then v_expected:=v_r.sleep_time; elsif upper(p_type)='WAKE' then v_expected:=v_r.wake_time; else raise exception 'INVALID_CHECKIN_TYPE'; end if;
 v_local:=p_occurred_at at time zone coalesce(v_r.timezone,'UTC');
 v_delta:=round(extract(epoch from ((v_local::time)-v_expected))/60.0)::int;
 if abs(v_delta)<=coalesce(v_r.verification_minutes,10) then v_status:='ON_TIME'; elsif v_delta>0 then v_status:='LATE'; else v_status:='EARLY'; end if;
 insert into public.routine_checkins(user_id,checkin_type,occurred_at,expected_local_time,timezone,status,delta_minutes,metadata)
 values(v_user,upper(p_type),p_occurred_at,v_expected,coalesce(v_r.timezone,'UTC'),v_status,v_delta,coalesce(p_metadata,'{}'::jsonb)) returning id into v_id;
 return jsonb_build_object('id',v_id,'status',v_status,'delta_minutes',v_delta,'expected_time',v_expected,'occurred_at',p_occurred_at);
end $$;

create or replace function public.system_generate_daily_quests(p_for_date date default current_date)
returns jsonb language plpgsql security definer set search_path=public as $$
declare v_user uuid:=auth.uid(); v_class text; v_level int; v_q record; v_count int:=0; v_ids jsonb:='[]'::jsonb;
begin
 if v_user is null then raise exception 'AUTH_REQUIRED'; end if;
 select class,level into v_class,v_level from public.profiles where id=v_user;
 if v_class is null then raise exception 'PROFILE_NOT_READY'; end if;
 for v_q in
   select q.* from public.quest_library q
   where q.active=true and q.min_level<=coalesce(v_level,1)
     and (q.class_affinity is null or cardinality(q.class_affinity)=0 or upper(v_class)=any(q.class_affinity))
     and coalesce(q.frequency,'DAILY') in ('DAILY','ANY')
     and not exists(select 1 from public.user_quests uq where uq.user_id=v_user and uq.quest_id=q.id and uq.assigned_for=p_for_date)
   order by case when upper(v_class)=any(coalesce(q.class_affinity,array[]::text[])) then 0 else 1 end, q.health_value desc nulls last, q.xp_reward desc
   limit 4
 loop
   insert into public.user_quests(user_id,quest_id,assigned_for,quest_type,title_snapshot,objective_snapshot,category,status,source,expires_at,xp_reward,xp_penalty,attribute_reward,attribute_delta,consequence,metadata)
   values(v_user,v_q.id,p_for_date,v_q.quest_type,v_q.title,v_q.objective,v_q.category,'ASSIGNED','SYSTEM',((p_for_date+1)::timestamp at time zone 'UTC'),v_q.xp_reward,v_q.failure_xp_penalty,v_q.attribute_reward,v_q.attribute_delta,case when coalesce(v_q.failure_xp_penalty,0)>0 then '-'||v_q.failure_xp_penalty||' XP' else null end,jsonb_build_object('generated_by','SYSTEM','library_code',v_q.code))
   returning id into v_q.id;
   v_ids:=v_ids||jsonb_build_array(v_q.id); v_count:=v_count+1;
 end loop;
 return jsonb_build_object('assigned',v_count,'quest_ids',v_ids,'date',p_for_date);
end $$;

create or replace function public.system_apply_expired_quest_penalties()
returns jsonb language plpgsql security definer set search_path=public as $$
declare v_user uuid:=auth.uid(); v_q record; v_count int:=0; v_total int:=0;
begin
 if v_user is null then raise exception 'AUTH_REQUIRED'; end if;
 for v_q in select * from public.user_quests where user_id=v_user and status in ('ASSIGNED','ACCEPTED') and expires_at is not null and expires_at<now() for update
 loop
   update public.user_quests set status='FAILED',failed_at=now(),updated_at=now() where id=v_q.id;
   if coalesce(v_q.xp_penalty,0)>0 then
     insert into public.quest_penalty_events(user_id,user_quest_id,xp_penalty,metadata) values(v_user,v_q.id,v_q.xp_penalty,jsonb_build_object('expired_at',v_q.expires_at)) on conflict(user_quest_id) do nothing;
     if found then update public.profiles set xp=greatest(0,coalesce(xp,0)-v_q.xp_penalty),updated_at=now() where id=v_user; v_total:=v_total+v_q.xp_penalty; end if;
   end if;
   v_count:=v_count+1;
 end loop;
 return jsonb_build_object('failed_quests',v_count,'xp_penalty_applied',v_total);
end $$;

