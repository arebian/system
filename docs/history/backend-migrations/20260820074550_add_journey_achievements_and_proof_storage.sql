create table public.journey_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  event_type text not null,
  title text not null,
  detail text,
  source text,
  source_id text,
  xp_delta integer not null default 0,
  attribute_name text check (attribute_name is null or attribute_name in ('STRENGTH','SPEED','ENDURANCE','INTELLIGENCE','FOCUS','DISCIPLINE','WEALTH','CHARISMA','CREATIVITY','RECOVERY')),
  attribute_delta integer,
  metadata jsonb not null default '{}'::jsonb,
  occurred_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create index journey_events_user_time_idx on public.journey_events(user_id, occurred_at desc);

create table public.achievements (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  description text,
  category text not null default 'GENERAL',
  rarity text not null default 'RARE' check (rarity in ('COMMON','RARE','EPIC','LEGENDARY','MYTHIC')),
  xp_reward integer not null default 0 check (xp_reward >= 0),
  icon text,
  criteria jsonb not null default '{}'::jsonb,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.user_achievements (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  achievement_id bigint not null references public.achievements(id) on delete cascade,
  progress numeric not null default 0,
  target numeric,
  unlocked boolean not null default false,
  unlocked_at timestamptz,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(user_id, achievement_id)
);

create table public.proof_records (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null,
  proof_type text not null default 'ACHIEVEMENT',
  note text,
  storage_path text,
  mime_type text,
  file_size bigint,
  related_event_type text,
  related_event_id text,
  metadata jsonb not null default '{}'::jsonb,
  captured_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

