create table public.item_catalog (
  id bigint generated by default as identity primary key,
  slug text unique not null,
  name text not null,
  item_type text not null,
  rarity text not null check (rarity in ('COMMON','UNCOMMON','RARE','EPIC','LEGENDARY','MYTHIC')),
  power integer not null default 0 check (power >= 0),
  required_level integer not null default 1 check (required_level >= 1),
  bonus_text text,
  icon text,
  metadata jsonb not null default '{}'::jsonb,
  active boolean not null default true,
  created_at timestamptz not null default now()
);

create table public.user_inventory (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  catalog_item_id bigint references public.item_catalog(id) on delete set null,
  custom_name text,
  custom_type text,
  rarity text check (rarity is null or rarity in ('COMMON','UNCOMMON','RARE','EPIC','LEGENDARY','MYTHIC')),
  bonus_text text,
  notes text,
  image_path text,
  source_type text,
  source_id text,
  equipped boolean not null default false,
  showcase boolean not null default false,
  acquired_at timestamptz not null default now(),
  metadata jsonb not null default '{}'::jsonb,
  check (catalog_item_id is not null or custom_name is not null)
);

create index user_inventory_user_idx on public.user_inventory(user_id);
create index user_inventory_equipped_idx on public.user_inventory(user_id,equipped);

create table public.rewards (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  name text not null,
  category text,
  source text,
  status text not null default 'UNCLAIMED' check (status in ('UNCLAIMED','CLAIMED','EXPIRED','DISMISSED')),
  claimed_at timestamptz,
  created_at timestamptz not null default now(),
  metadata jsonb not null default '{}'::jsonb
);

create index rewards_user_idx on public.rewards(user_id);
create index rewards_status_idx on public.rewards(user_id,status);

alter table public.item_catalog enable row level security;
alter table public.user_inventory enable row level security;
alter table public.rewards enable row level security;

grant select on table public.item_catalog to authenticated;
grant select,insert,update,delete on table public.user_inventory to authenticated;
grant select,insert,update,delete on table public.rewards to authenticated;
grant all on table public.item_catalog, public.user_inventory, public.rewards to service_role;
grant usage,select on sequence public.item_catalog_id_seq to authenticated;
grant usage,select on sequence public.user_inventory_id_seq to authenticated;
grant usage,select on sequence public.rewards_id_seq to authenticated;

create policy item_catalog_read on public.item_catalog for select to authenticated using (active = true);

create policy user_inventory_select_own on public.user_inventory for select to authenticated using ((select auth.uid()) = user_id);
create policy user_inventory_insert_own on public.user_inventory for insert to authenticated with check ((select auth.uid()) = user_id);
create policy user_inventory_update_own on public.user_inventory for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy user_inventory_delete_own on public.user_inventory for delete to authenticated using ((select auth.uid()) = user_id);

create policy rewards_select_own on public.rewards for select to authenticated using ((select auth.uid()) = user_id);
create policy rewards_insert_own on public.rewards for insert to authenticated with check ((select auth.uid()) = user_id);
create policy rewards_update_own on public.rewards for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy rewards_delete_own on public.rewards for delete to authenticated using ((select auth.uid()) = user_id);
