create table public.skills (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  class_affinity text[] not null default '{}',
  category text not null,
  difficulty text not null check (difficulty in ('BEGINNER','INTERMEDIATE','ADVANCED','ELITE','LEGENDARY')),
  description text,
  progression_group text,
  unlock_level integer not null default 1 check (unlock_level >= 1),
  xp_reward integer not null default 0 check (xp_reward >= 0),
  primary_attribute text check (primary_attribute is null or primary_attribute in ('STRENGTH','SPEED','ENDURANCE','INTELLIGENCE','FOCUS','DISCIPLINE','WEALTH','CHARISMA','CREATIVITY','RECOVERY')),
  equipment text,
  safety_notes text,
  is_active boolean not null default true,
  sort_order integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.skill_prerequisites (
  skill_id bigint not null references public.skills(id) on delete cascade,
  prerequisite_skill_id bigint not null references public.skills(id) on delete cascade,
  minimum_status text not null default 'MASTERED' check (minimum_status in ('AVAILABLE','PRACTICING','MASTERED')),
  primary key (skill_id, prerequisite_skill_id),
  check (skill_id <> prerequisite_skill_id)
);

create table public.user_skills (
  user_id uuid not null references auth.users(id) on delete cascade,
  skill_id bigint not null references public.skills(id) on delete cascade,
  status text not null default 'LOCKED' check (status in ('LOCKED','AVAILABLE','PRACTICING','MASTERED')),
  progress_value numeric,
  progress_unit text,
  best_value numeric,
  attempts integer not null default 0 check (attempts >= 0),
  notes text,
  started_at timestamptz,
  mastered_at timestamptz,
  updated_at timestamptz not null default now(),
  primary key (user_id, skill_id)
);

alter table public.skills enable row level security;
alter table public.skill_prerequisites enable row level security;
alter table public.user_skills enable row level security;

revoke all on table public.skills from anon;
revoke all on table public.skill_prerequisites from anon;
revoke all on table public.user_skills from anon;

grant select on table public.skills to authenticated;
grant select on table public.skill_prerequisites to authenticated;
grant select, insert, update, delete on table public.user_skills to authenticated;
grant all on table public.skills to service_role;
grant all on table public.skill_prerequisites to service_role;
grant all on table public.user_skills to service_role;

create policy "skills_read_authenticated"
on public.skills
for select
to authenticated
using (is_active = true);

create policy "skill_prerequisites_read_authenticated"
on public.skill_prerequisites
for select
to authenticated
using (true);

create policy "user_skills_select_own"
on public.user_skills
for select
to authenticated
using ((select auth.uid()) = user_id);

create policy "user_skills_insert_own"
on public.user_skills
for insert
to authenticated
with check ((select auth.uid()) = user_id);

create policy "user_skills_update_own"
on public.user_skills
for update
to authenticated
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);

create policy "user_skills_delete_own"
on public.user_skills
for delete
to authenticated
using ((select auth.uid()) = user_id);

create index user_skills_user_status_idx on public.user_skills(user_id, status);
create index skills_progression_group_idx on public.skills(progression_group, sort_order);
create index skills_category_idx on public.skills(category, difficulty);

