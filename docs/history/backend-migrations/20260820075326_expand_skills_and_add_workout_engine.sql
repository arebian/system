alter table public.skills
  add column if not exists mastery_metric text,
  add column if not exists mastery_target numeric,
  add column if not exists mastery_unit text,
  add column if not exists mastery_notes text;

create table if not exists public.workout_templates (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  category text not null,
  difficulty text not null check (difficulty in ('BEGINNER','INTERMEDIATE','ADVANCED','ELITE')),
  focus text[] not null default '{}',
  class_affinity text[] not null default '{}',
  description text,
  estimated_minutes integer check (estimated_minutes is null or estimated_minutes > 0),
  xp_reward integer not null default 0 check (xp_reward >= 0),
  equipment text,
  safety_notes text,
  active boolean not null default true,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.workout_steps (
  id bigint generated by default as identity primary key,
  workout_id bigint not null references public.workout_templates(id) on delete cascade,
  position integer not null default 0,
  exercise_name text not null,
  sets integer,
  reps text,
  duration_seconds integer,
  rest_seconds integer,
  notes text,
  metadata jsonb not null default '{}'::jsonb
);

create table if not exists public.workout_skill_requirements (
  workout_id bigint not null references public.workout_templates(id) on delete cascade,
  skill_id bigint not null references public.skills(id) on delete cascade,
  minimum_status text not null default 'AVAILABLE' check (minimum_status in ('AVAILABLE','PRACTICING','MASTERED')),
  primary key (workout_id, skill_id)
);

create table if not exists public.user_workout_sessions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  workout_id bigint references public.workout_templates(id) on delete set null,
  workout_name_snapshot text not null,
  status text not null default 'STARTED' check (status in ('STARTED','COMPLETED','ABANDONED')),
  started_at timestamptz not null default now(),
  completed_at timestamptz,
  duration_seconds integer check (duration_seconds is null or duration_seconds >= 0),
  perceived_difficulty integer check (perceived_difficulty is null or perceived_difficulty between 1 and 5),
  notes text,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists workout_steps_workout_idx on public.workout_steps(workout_id, position);
create index if not exists workout_skill_requirements_skill_idx on public.workout_skill_requirements(skill_id);
create index if not exists user_workout_sessions_user_time_idx on public.user_workout_sessions(user_id, started_at desc);
create index if not exists user_workout_sessions_workout_idx on public.user_workout_sessions(workout_id);

alter table public.workout_templates enable row level security;
alter table public.workout_steps enable row level security;
alter table public.workout_skill_requirements enable row level security;
alter table public.user_workout_sessions enable row level security;

revoke all on public.workout_templates from anon;
revoke all on public.workout_steps from anon;
revoke all on public.workout_skill_requirements from anon;
revoke all on public.user_workout_sessions from anon;

grant select on public.workout_templates to authenticated;
grant select on public.workout_steps to authenticated;
grant select on public.workout_skill_requirements to authenticated;
grant select, insert, update, delete on public.user_workout_sessions to authenticated;

drop policy if exists workout_templates_read on public.workout_templates;
create policy workout_templates_read on public.workout_templates for select to authenticated using (active = true);

drop policy if exists workout_steps_read on public.workout_steps;
create policy workout_steps_read on public.workout_steps for select to authenticated using (exists (select 1 from public.workout_templates w where w.id = workout_steps.workout_id and w.active = true));

drop policy if exists workout_skill_requirements_read on public.workout_skill_requirements;
create policy workout_skill_requirements_read on public.workout_skill_requirements for select to authenticated using (true);

drop policy if exists user_workout_sessions_select_own on public.user_workout_sessions;
create policy user_workout_sessions_select_own on public.user_workout_sessions for select to authenticated using ((select auth.uid()) = user_id);

drop policy if exists user_workout_sessions_insert_own on public.user_workout_sessions;
create policy user_workout_sessions_insert_own on public.user_workout_sessions for insert to authenticated with check ((select auth.uid()) = user_id);

drop policy if exists user_workout_sessions_update_own on public.user_workout_sessions;
create policy user_workout_sessions_update_own on public.user_workout_sessions for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);

drop policy if exists user_workout_sessions_delete_own on public.user_workout_sessions;
create policy user_workout_sessions_delete_own on public.user_workout_sessions for delete to authenticated using ((select auth.uid()) = user_id);
