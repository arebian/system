const cloudSingleFlights =
  new Map();

function runCloudSingleFlight(
  key,
  task
) {
  const existing =
    cloudSingleFlights.get(
      key
    );

  if (existing) {
    return existing;
  }

  let flight;

  flight =
    Promise.resolve()
      .then(task)
      .finally(() => {
        if (
          cloudSingleFlights.get(
            key
          ) === flight
        ) {
          cloudSingleFlights.delete(
            key
          );
        }
      });

  cloudSingleFlights.set(
    key,
    flight
  );

  return flight;
}


function localCalendarDateKey(value = new Date()) {
  const date = value instanceof Date ? value : new Date(value);
  return [
    date.getFullYear(),
    String(date.getMonth() + 1).padStart(2, "0"),
    String(date.getDate()).padStart(2, "0"),
  ].join("-");
}

const SYSTEM_API_TIMEOUT_MS = 15000;

function withCloudTimeout(
  promise,
  timeoutMs = SYSTEM_API_TIMEOUT_MS,
  code = "SYSTEM_API_TIMEOUT"
) {
  let timer = null;

  const timeout = new Promise((_, reject) => {
    timer = setTimeout(() => {
      const error = new Error(code);
      error.code = code;
      reject(error);
    }, timeoutMs);
  });

  return Promise.race([promise, timeout]).finally(() => {
    if (timer) {
      clearTimeout(timer);
    }
  });
}


