-- Generic updated_at helper for new backend-owned records.
create or replace function public.set_updated_at()
returns trigger
language plpgsql
security invoker
set search_path = public
as $$
begin
  new.updated_at = now();
  return new;
end;
$$;

drop trigger if exists gps_sessions_set_updated_at on public.gps_sessions;
create trigger gps_sessions_set_updated_at
before update on public.gps_sessions
for each row execute function public.set_updated_at();

drop trigger if exists player_routines_set_updated_at on public.player_routines;
create trigger player_routines_set_updated_at
before update on public.player_routines
for each row execute function public.set_updated_at();

drop trigger if exists system_intelligence_threads_set_updated_at on public.system_intelligence_threads;
create trigger system_intelligence_threads_set_updated_at
before update on public.system_intelligence_threads
for each row execute function public.set_updated_at();

-- Server-side XP progression helper. Frontends request actions; DB owns arithmetic.
create or replace function public.system_xp_required(p_level integer)
returns integer
language sql
immutable
security invoker
set search_path = public
as $$
  select greatest(10, round(10 * power(greatest(p_level,1)::numeric, 1.62))::integer);
$$;

create or replace function public.system_award_xp(
  p_amount integer,
  p_source text default 'SYSTEM',
  p_title text default 'XP AWARD',
  p_metadata jsonb default '{}'::jsonb
)
returns public.profiles
language plpgsql
security invoker
set search_path = public, auth
as $$
declare
  v_user uuid := auth.uid();
  v_profile public.profiles;
  v_before_level integer;
  v_remaining integer;
  v_required integer;
begin
  if v_user is null then
    raise exception 'AUTH_REQUIRED';
  end if;
  if p_amount < 0 then
    raise exception 'XP_AMOUNT_MUST_BE_NONNEGATIVE';
  end if;

  select * into v_profile from public.profiles where id = v_user for update;
  if not found then
    raise exception 'PROFILE_NOT_FOUND';
  end if;

  v_before_level := v_profile.level;
  v_remaining := v_profile.xp + p_amount;

  loop
    v_required := public.system_xp_required(v_profile.level);
    exit when v_remaining < v_required;
    v_remaining := v_remaining - v_required;
    v_profile.level := v_profile.level + 1;
  end loop;

  update public.profiles
  set xp = v_remaining,
      level = v_profile.level,
      updated_at = now()
  where id = v_user
  returning * into v_profile;

  insert into public.progression_events(
    user_id,event_type,source,title,xp_delta,level_before,level_after,metadata
  ) values (
    v_user,
    case when v_profile.level <> v_before_level then 'LEVEL_CHANGE' else 'XP_CHANGE' end,
    p_source,
    p_title,
    p_amount,
    v_before_level,
    v_profile.level,
    coalesce(p_metadata,'{}'::jsonb)
  );

  return v_profile;
end;
$$;

-- Boss damage is atomic, logged and backend-owned.
create or replace function public.system_damage_active_boss(
  p_damage integer,
  p_source_type text,
  p_source_id text default null,
  p_source_name text default null,
  p_metadata jsonb default '{}'::jsonb
)
returns public.boss_quests
language plpgsql
security invoker
set search_path = public, auth
as $$
declare
  v_user uuid := auth.uid();
  v_boss public.boss_quests;
  v_before integer;
begin
  if v_user is null then
    raise exception 'AUTH_REQUIRED';
  end if;
  if p_damage <= 0 then
    raise exception 'DAMAGE_MUST_BE_POSITIVE';
  end if;

  select * into v_boss
  from public.boss_quests
  where user_id = v_user and status = 'ACTIVE'
  order by created_at desc
  limit 1
  for update;

  if not found then
    raise exception 'NO_ACTIVE_BOSS';
  end if;

  v_before := v_boss.hp;
  v_boss.hp := greatest(0, v_boss.hp - p_damage);

  update public.boss_quests
  set hp = v_boss.hp,
      metadata = coalesce(metadata,'{}'::jsonb) || jsonb_build_object('last_damage_at',now())
  where id = v_boss.id
  returning * into v_boss;

  insert into public.boss_damage_events(
    user_id,boss_quest_id,source_type,source_id,source_name,damage,hp_before,hp_after,metadata
  ) values (
    v_user,v_boss.id,p_source_type,p_source_id,p_source_name,
    least(p_damage,v_before),v_before,v_boss.hp,coalesce(p_metadata,'{}'::jsonb)
  );

  return v_boss;
end;
$$;

-- Weekly report function gives every future frontend the same summary contract.
create or replace function public.system_weekly_snapshot(
  p_week_start date default (current_date - extract(dow from current_date)::integer)
)
returns jsonb
language plpgsql
security invoker
set search_path = public, auth
as $$
declare
  v_user uuid := auth.uid();
  v_week_end date := p_week_start + 6;
  v_result jsonb;
begin
  if v_user is null then raise exception 'AUTH_REQUIRED'; end if;

  select jsonb_build_object(
    'week_start', p_week_start,
    'week_end', v_week_end,
    'xp_gained', coalesce((select sum(greatest(xp_delta,0)) from public.progression_events where user_id=v_user and created_at >= p_week_start and created_at < v_week_end + 1),0),
    'quests_completed', (select count(*) from public.user_quests where user_id=v_user and status='COMPLETED' and completed_at >= p_week_start and completed_at < v_week_end + 1),
    'quests_failed', (select count(*) from public.user_quests where user_id=v_user and status='FAILED' and failed_at >= p_week_start and failed_at < v_week_end + 1),
    'workouts_completed', (select count(*) from public.user_workout_sessions where user_id=v_user and status='COMPLETED' and completed_at >= p_week_start and completed_at < v_week_end + 1),
    'gps_distance_km', coalesce((select sum(distance_km) from public.gps_sessions where user_id=v_user and gps_verified=true and started_at >= p_week_start and started_at < v_week_end + 1),0),
    'skills_mastered', (select count(*) from public.user_skills where user_id=v_user and status='MASTERED' and mastered_at >= p_week_start and mastered_at < v_week_end + 1),
    'boss_damage', coalesce((select sum(damage) from public.boss_damage_events where user_id=v_user and created_at >= p_week_start and created_at < v_week_end + 1),0),
    'bosses_defeated', (select count(*) from public.boss_quests where user_id=v_user and status='COMPLETE' and completed_at >= p_week_start and completed_at < v_week_end + 1)
  ) into v_result;

  return v_result;
end;
$$;

-- RLS for new player-owned tables.
alter table public.boss_damage_events enable row level security;
alter table public.gps_sessions enable row level security;
alter table public.player_routines enable row level security;
alter table public.class_history enable row level security;
alter table public.weekly_system_reports enable row level security;
alter table public.system_intelligence_threads enable row level security;
alter table public.system_intelligence_messages enable row level security;

-- Recreate idempotent own-row policies.
do $$
declare
  t text;
begin
  foreach t in array array['boss_damage_events','gps_sessions','player_routines','class_history','weekly_system_reports','system_intelligence_threads','system_intelligence_messages'] loop
    execute format('drop policy if exists %I on public.%I', t || '_select_own', t);
    execute format('drop policy if exists %I on public.%I', t || '_insert_own', t);
    execute format('drop policy if exists %I on public.%I', t || '_update_own', t);
    execute format('drop policy if exists %I on public.%I', t || '_delete_own', t);
    execute format('create policy %I on public.%I for select to authenticated using ((select auth.uid()) = user_id)', t || '_select_own', t);
    execute format('create policy %I on public.%I for insert to authenticated with check ((select auth.uid()) = user_id)', t || '_insert_own', t);
    execute format('create policy %I on public.%I for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id)', t || '_update_own', t);
    execute format('create policy %I on public.%I for delete to authenticated using ((select auth.uid()) = user_id)', t || '_delete_own', t);
  end loop;
end $$;

-- Seed backend-owned routine/preferences/evolution rows for existing profiles.
insert into public.player_routines(user_id, timezone)
select p.id, coalesce(pref.timezone,'UTC')
from public.profiles p
left join public.user_preferences pref on pref.user_id=p.id
on conflict (user_id) do nothing;

insert into public.class_history(user_id, from_class, to_class, reason, changed_at)
select p.id, null, p.class, 'MIGRATED_BASELINE', coalesce(p.created_at,now())
from public.profiles p
where not exists (
  select 1 from public.class_history h where h.user_id=p.id
);

commit;
