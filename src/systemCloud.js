export async function completeQuestByTitleOnBackend({
  title,
  context = "QUEST",
  proof = null,
  legacyKey = null,
  assignedFor = null,
}) {
  const normalizedTitle = String(title || "").trim();
  if (!normalizedTitle) {
    throw new Error("QUEST_TITLE_REQUIRED");
  }

  const effectiveDate = assignedFor || localCalendarDateKey();

  return runCloudSingleFlight(
    "quest-complete:" +
      effectiveDate +
      ":" +
      normalizedTitle
        .toUpperCase(),
    async () => {
      if (proof?.type !== "TIME") proof = { ...proof, ...normalizeReviewProof(proof || {}) };
      if (proof?.type !== "TIME" && !proof?.reviewId) {
        const assessment = await reviewQuestOnBackend({ title: normalizedTitle, assignedFor: effectiveDate, proof: proof || {}, verificationMode: proof?.verificationMode || "AI" });
        if (assessment.decision !== "APPROVE") throw new Error([assessment.reason, assessment.question].filter(Boolean).join(" "));
        proof = { ...proof, reviewId: assessment.id };
      }
      const {
        data,
        error,
      } =
        await withCloudTimeout(
          supabase.rpc(
            "system_complete_quest_by_title_v2",
            {
              p_title:
                normalizedTitle,
              p_assigned_for:
                effectiveDate,
              p_metadata: {
                client:
                  "PLATFORM_V2",
                context,
                legacy_key:
                  legacyKey,
                proof_review_id: proof?.reviewId || null,
                proof_honor_confirmed: proof?.honorConfirmed === true,
                proof_type:
                  proof?.type ||
                  "HONOR",
                proof_verified_at:
                  proof?.verifiedAt ||
                  null,
                proof_detail:
                  proof?.detail ||
                  null,
                proof_note:
                  proof?.note ||
                  null,
                proof_takeaways:
                  Array.isArray(
                    proof?.takeaways
                  )
                    ? proof.takeaways
                    : [],
                proof_image_path:
                  proof?.imagePath ||
                  null,
              },
            }
          ),
          SYSTEM_API_TIMEOUT_MS,
          "QUEST_COMPLETION_TIMEOUT"
        );

      if (error) {
        throw error;
      }

      return {
        data,
      };
    }
  );
}

