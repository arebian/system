export async function loadTrainingCatalog() {
  // Load the skill tree independently from the supporting
  // workout tables. A workout/step failure must never erase
  // an otherwise healthy skill tree.

  const skillsResult =
    await runTrainingCatalogQuery(
      () =>
        supabase
          .from("skills")
          .select("*")
          .eq(
            "is_active",
            true
          )
          .order(
            "sort_order",
            {
              ascending:
                true,
            }
          )
    );

  if (
    skillsResult.error
  ) {
    throw skillsResult.error;
  }

  const [
    prerequisiteResult,
    workoutResult,
    stepResult,
    requirementResult,
  ] =
    await Promise.all([
      runTrainingCatalogQuery(
        () =>
          supabase
            .from(
              "skill_prerequisites"
            )
            .select("*")
      ),

      runTrainingCatalogQuery(
        () =>
          supabase
            .from(
              "workout_templates"
            )
            .select("*")
            .eq(
              "active",
              true
            )
            .order(
              "difficulty",
              {
                ascending:
                  true,
              }
            )
      ),

      runTrainingCatalogQuery(
        () =>
          supabase
            .from(
              "workout_steps"
            )
            .select("*")
            .order(
              "position",
              {
                ascending:
                  true,
              }
            )
      ),

      runTrainingCatalogQuery(
        () =>
          supabase
            .from(
              "workout_skill_requirements"
            )
            .select("*")
      ),
    ]);

  const warnings = [];

  if (
    prerequisiteResult.error
  ) {
    console.error(
      "SKILL PREREQUISITES LOAD FAILED:",
      prerequisiteResult.error
    );

    warnings.push(
      "PREREQUISITES OFFLINE"
    );
  }

  if (
    workoutResult.error
  ) {
    console.error(
      "WORKOUT CATALOG LOAD FAILED:",
      workoutResult.error
    );

    warnings.push(
      "WORKOUTS OFFLINE"
    );
  }

  if (
    stepResult.error
  ) {
    console.error(
      "WORKOUT STEPS LOAD FAILED:",
      stepResult.error
    );

    warnings.push(
      "WORKOUT STEPS OFFLINE"
    );
  }

  if (
    requirementResult.error
  ) {
    console.error(
      "WORKOUT REQUIREMENTS LOAD FAILED:",
      requirementResult.error
    );

    warnings.push(
      "SKILL/WORKOUT LINKS OFFLINE"
    );
  }

  const safePrerequisites =
    prerequisiteResult.error
      ? []
      : prerequisiteResult.data ||
        [];

  const safeWorkouts =
    workoutResult.error
      ? []
      : workoutResult.data ||
        [];

  const safeSteps =
    stepResult.error
      ? []
      : stepResult.data ||
        [];

  const safeRequirements =
    requirementResult.error
      ? []
      : requirementResult.data ||
        [];

  const stepsByWorkout =
    new Map();

  safeSteps.forEach(
    (step) => {
      const list =
        stepsByWorkout.get(
          step.workout_id
        ) || [];

      list.push(step);

      stepsByWorkout.set(
        step.workout_id,
        list
      );
    }
  );

  return {
    skills:
      skillsResult.data ||
      [],

    prerequisites:
      safePrerequisites,

    workouts:
      safeWorkouts.map(
        (workout) => ({
          ...workout,
          steps:
            stepsByWorkout.get(
              workout.id
            ) || [],
        })
      ),

    requirements:
      safeRequirements,

    warning:
      warnings.join(
        " • "
      ),
  };
}

