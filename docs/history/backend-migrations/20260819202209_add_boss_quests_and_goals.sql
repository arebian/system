create table public.boss_quests (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null check (char_length(title) between 1 and 120),
  rank text not null check (rank in ('C','B','A','S')),
  category text not null default 'DISCIPLINE',
  status text not null default 'ACTIVE' check (status in ('ACTIVE','COMPLETE','FAILED','ABANDONED')),
  xp_reward integer not null default 0 check (xp_reward >= 0),
  reward_name text,
  reward_rarity text,
  deadline timestamptz,
  created_at timestamptz not null default now(),
  completed_at timestamptz,
  metadata jsonb not null default '{}'::jsonb
);

create table public.boss_quest_objectives (
  id bigint generated by default as identity primary key,
  boss_quest_id bigint not null references public.boss_quests(id) on delete cascade,
  user_id uuid not null references auth.users(id) on delete cascade,
  position integer not null default 0,
  objective text not null check (char_length(objective) between 1 and 240),
  is_complete boolean not null default false,
  completed_at timestamptz,
  created_at timestamptz not null default now()
);

create table public.goals (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title text not null check (char_length(title) between 1 and 120),
  category text not null default 'OTHER',
  target_value numeric not null check (target_value > 0),
  current_value numeric not null default 0 check (current_value >= 0),
  unit text,
  deadline date,
  status text not null default 'ACTIVE' check (status in ('ACTIVE','COMPLETE','ARCHIVED')),
  xp_reward integer not null default 300 check (xp_reward >= 0),
  reward_name text,
  created_at timestamptz not null default now(),
  completed_at timestamptz,
  metadata jsonb not null default '{}'::jsonb
);

alter table public.boss_quests enable row level security;
alter table public.boss_quest_objectives enable row level security;
alter table public.goals enable row level security;

grant select, insert, update, delete on public.boss_quests to authenticated;
grant select, insert, update, delete on public.boss_quest_objectives to authenticated;
grant select, insert, update, delete on public.goals to authenticated;

create policy boss_quests_select_own on public.boss_quests for select to authenticated using ((select auth.uid()) = user_id);
create policy boss_quests_insert_own on public.boss_quests for insert to authenticated with check ((select auth.uid()) = user_id);
create policy boss_quests_update_own on public.boss_quests for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy boss_quests_delete_own on public.boss_quests for delete to authenticated using ((select auth.uid()) = user_id);

create policy boss_objectives_select_own on public.boss_quest_objectives for select to authenticated using ((select auth.uid()) = user_id);
create policy boss_objectives_insert_own on public.boss_quest_objectives for insert to authenticated with check ((select auth.uid()) = user_id);
create policy boss_objectives_update_own on public.boss_quest_objectives for update to authenticated using ((select auth.uid()) = user_id) with check ((select auth.uid()) = user_id);
create policy boss_objectives_delete_own on public.boss_quest_objectives for delete to authenticated using ((select auth.uid()) = user_id);

create policy goals_select_own on public.goals for select to authenticated using ((select auth.uid()) = user_id);
