export async function bootstrapAuthoritativeProfile() {
  const response =
    await invokeSystemApi(
      "bootstrap"
    );

  const state =
    response?.data;

  // The bootstrap preparation timestamp is generated by the backend in the
  // same response as active quests. It lets countdowns stay accurate when a
  // device clock is ahead or behind without making the browser authoritative.
  const serverClockOffsetMs =
    getServerClockOffsetMs(
      state?.server_now ||
      state?.preparation?.prepared_at
    );

  const row =
    state?.profile;

  if (!row) {
    return null;
  }

  const base =
    (
      row.profile_data &&
      typeof row.profile_data ===
        "object" &&
      !Array.isArray(
        row.profile_data
      )
    )
      ? {
          ...row.profile_data,
        }
      : {};

  const attributes =
    mapApiAttributes(
      state?.attributes
    );

  const routine =
    state?.routine;

  const legacy = {
    ...base,
    equipment: state?.equipment || null,

    name:
      row.name ??
      base.name,

    age:
      row.age ??
      base.age,

    gender:
      row.gender ??
      base.gender ??
      "",

    path:
      row.class ??
      base.path,

    level:
      Number(
        row.level
      ) || 1,

    xp:
      Number(
        row.xp
      ) || 0,

    streak:
      Number(
        row.streak
      ) || 0,

    momentum:
      Number(
        row.momentum
      ) || 0,

    fingerprint:
      row.fingerprint ??
      base.fingerprint ??
      null,

    ...(attributes
      ? {
          attributes,
        }
      : {}),

    ...(routine
      ? {
          sleepSchedule: {
            ...(
              base.sleepSchedule ||
              {}
            ),

            mode:
              routine.shift_mode ??
              base.sleepSchedule?.mode ??
              "STANDARD",

            sleep:
              routine.sleep_time ??
              base.sleepSchedule?.sleep ??
              "22:00",

            wake:
              routine.wake_time ??
              base.sleepSchedule?.wake ??
              "06:00",

            verificationMinutes:
              Number(
                routine.verification_minutes
              ) || 10,

            timezone:
              routine.timezone ??
              base.sleepSchedule?.timezone ??
              "UTC",
          },
        }
      : {}),
  };

  // Store additional authoritative state without changing
  // any existing UI contracts yet. Future phases can consume it.

  // Preserve legacy UI-only quest bookkeeping from the local cache.
  // Authoritative values such as XP, level, attributes, streak and momentum
  // are NEVER taken from this cache.
  try {
    const cachedRaw =
      typeof localStorage !== "undefined"
        ? localStorage.getItem(
            "systemProfile"
          )
        : null;

    const cached =
      cachedRaw
        ? JSON.parse(
            cachedRaw
          )
        : null;

    const uiOnlyKeys = [
      "dailyCompleted",
      "mustState",
      "questProofs",
      "wakeProofs",
      "completed",
      "questLog",
      "history",
      "pendingConsequences",
      // These are personal planning/reader presentation records only. They
      // deliberately never replace server-owned XP, attributes, timers or
      // official Archive progression during a cloud bootstrap.
      "fuel",
      "archiveFallback",
      "classTrainingLog",
    ];

    if (
      cached &&
      typeof cached ===
        "object"
    ) {
      uiOnlyKeys.forEach(
        (key) => {
          if (
            cached[key] != null
          ) {
            legacy[key] =
              cached[key];
          }
        }
      );
    }
  } catch {
    // A corrupt local cache must never block authoritative bootstrap.
  }

  // Reconcile accepted Must Quests back into the UI cache. The server
  // is authoritative for acceptance timestamps and expiry timers.
  const authoritativeMustState = {};

  for (const row of state?.activeQuests || []) {
    if (String(row?.quest_type || "").toUpperCase() !== "MUST") {
      continue;
    }

    const legacyKey = row?.metadata?.legacy_key || null;
    if (!legacyKey) {
      continue;
    }

    authoritativeMustState[legacyKey] = {
      ...((legacy.mustState || {})[legacyKey] || {}),
      accepted: row.status === "ACCEPTED",
      mandatory: true,
      completed: false,
      failed: false,
      penaltyApplied: false,
      penalty: Number(row.xp_penalty || 0),
      name: row.title_snapshot || "MUST QUEST",
      date: String(row.assigned_for || ""),
      generatedAt: row.accepted_at || row.created_at || null,
      acceptedAt: row.accepted_at || null,
      expiresAt: row.expires_at || null,
      serverOffsetMs: serverClockOffsetMs,
      authoritative: true,
      backendQuestId: row.id || null,
      syncStatus: row.status === "ACCEPTED" ? "READY" : "ASSIGNED",
    };
  }

  if (Object.keys(authoritativeMustState).length) {
    legacy.mustState = {
      ...(legacy.mustState || {}),
      ...authoritativeMustState,
    };
  }


  const authoritativeMasteredSkills = {};

  for (
    const row of
      state?.skills || []
  ) {
    const skill =
      row?.skills;

    if (
      row?.status ===
        "MASTERED" &&
      skill?.name
    ) {
      authoritativeMasteredSkills[
        skill.name
      ] = true;
    }
  }

  legacy.masteredSkills =
    authoritativeMasteredSkills;


  const authoritativeTitles =
    (
      state?.titles || []
    ).map(
      (row) => ({
        id:
          "TITLE-" +
          row.title_id,
        userTitleId:
          row.id,
        name:
          row.title_catalog?.name ||
          "SYSTEM TITLE",
        slug:
          row.title_catalog?.slug ||
          "",
        category:
          row.title_catalog?.category ||
          "SYSTEM",
        rarity:
          row.title_catalog?.rarity ||
          "COMMON",
        icon:
          row.title_catalog?.icon ||
          "◆",
        description:
          row.title_catalog?.description ||
          "",
        equipped:
          Boolean(
            row.equipped
          ),
        unlockedAt:
          row.unlocked_at ||
          null,
        classAffinity:
          row.title_catalog?.class_affinity ||
          null,
        minimumLevel:
          Number(
            row.title_catalog?.minimum_level ||
            1
          ),
      })
    );


  const authoritativeAchievements =
    (
      state?.achievements || []
    ).map(
      (row) => ({
        id:
          row.achievements?.id ||
          row.achievement_id,
        slug:
          row.achievements?.slug ||
          "",
        name:
          row.achievements?.name ||
          "ACHIEVEMENT",
        description:
          row.achievements?.description ||
          "",
        category:
          row.achievements?.category ||
          "SYSTEM",
        rarity:
          row.achievements?.rarity ||
          "COMMON",
        xp_reward:
          Number(
            row.achievements?.xp_reward ||
            0
          ),
        icon:
          row.achievements?.icon ||
          "◆",
        progress:
          Number(
            row.progress ||
            0
          ),
        target:
          Number(
            row.target ||
            1
          ),
        unlocked:
          Boolean(
            row.unlocked
          ),
        unlockedAt:
          row.unlocked_at ||
          null,
      })
    );

  if (
    authoritativeAchievements.length
  ) {
    legacy.cloudAchievements =
      authoritativeAchievements;
  }

  legacy.cloudTitles =
    authoritativeTitles;

  legacy.equippedTitle =
    authoritativeTitles.find(
      (title) =>
        title.equipped
    ) || null;

  legacy.backendState = {
    version: 7,
    source:
      "SYSTEM_API",
    activeBoss:
      state?.activeBoss ??
      null,
    activeQuests:
      state?.activeQuests ??
      [],
    skills:
      state?.skills ??
      [],
    inventory:
      state?.inventory ??
      [],
    achievements:
      state?.achievements ??
      [],
    titles:
      state?.titles ??
      [],
    preferences:
      state?.preferences ??
      null,
    bootstrappedAt:
      new Date()
        .toISOString(),
  };

  return legacy;
}

