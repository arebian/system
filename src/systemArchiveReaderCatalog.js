export function getSystemPublicDomainEdition(book) {
  const candidates = [
    book?.embedded_reader_key,
    book?.slug,
  ]
    .map((value) => String(value || "").trim().toLowerCase())
    .filter(Boolean);

  for (const key of candidates) {
    if (SYSTEM_PUBLIC_DOMAIN_EDITIONS[key]) {
      return SYSTEM_PUBLIC_DOMAIN_EDITIONS[key];
    }
  }

  return null;
}
