create table public.attributes (
  user_id uuid primary key references auth.users(id) on delete cascade,
  strength integer not null default 10 check (strength >= 0),
  speed integer not null default 10 check (speed >= 0),
  endurance integer not null default 10 check (endurance >= 0),
  intelligence integer not null default 10 check (intelligence >= 0),
  focus integer not null default 10 check (focus >= 0),
  discipline integer not null default 10 check (discipline >= 0),
  wealth integer not null default 10 check (wealth >= 0),
  charisma integer not null default 10 check (charisma >= 0),
  creativity integer not null default 10 check (creativity >= 0),
  recovery integer not null default 10 check (recovery >= 0),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

alter table public.attributes enable row level security;
revoke all on table public.attributes from anon;
grant select, insert, update, delete on table public.attributes to authenticated;
grant all on table public.attributes to service_role;

create policy "attributes_select_own"
on public.attributes
for select
to authenticated
using ((select auth.uid()) = user_id);

create policy "attributes_insert_own"
on public.attributes
for insert
to authenticated
with check ((select auth.uid()) = user_id);

create policy "attributes_update_own"
on public.attributes
for update
to authenticated
using ((select auth.uid()) = user_id)
with check ((select auth.uid()) = user_id);

create policy "attributes_delete_own"
on public.attributes
for delete
to authenticated
using ((select auth.uid()) = user_id);

create table public.progression_events (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  event_type text not null,
  source text,
  title text not null,
  xp_delta integer not null default 0,
  level_before integer,
  level_after integer,
  attribute_name text check (attribute_name is null or attribute_name in ('STRENGTH','SPEED','ENDURANCE','INTELLIGENCE','FOCUS','DISCIPLINE','WEALTH','CHARISMA','CREATIVITY','RECOVERY')),
  attribute_delta integer,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index progression_events_user_id_created_at_idx
on public.progression_events (user_id, created_at desc);

