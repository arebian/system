create table public.title_catalog (
  id bigint generated by default as identity primary key,
  slug text not null unique,
  name text not null,
  category text not null default 'GENERAL',
  rarity text not null default 'COMMON' check (rarity in ('COMMON','UNCOMMON','RARE','EPIC','LEGENDARY','MYTHIC')),
  class_affinity text check (class_affinity is null or class_affinity in ('ASSASSIN','TANK','MAGE','RANGER','COMMANDER')),
  minimum_level integer not null default 1 check (minimum_level >= 1),
  icon text,
  description text,
  active boolean not null default true,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table public.user_titles (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  title_id bigint not null references public.title_catalog(id) on delete cascade,
  source text,
  equipped boolean not null default false,
  unlocked_at timestamptz not null default now(),
  metadata jsonb not null default '{}'::jsonb,
  unique(user_id,title_id)
);

create table public.player_evolutions (
  user_id uuid primary key references auth.users(id) on delete cascade,
  awakened boolean not null default false,
  class_at_ascension text check (class_at_ascension is null or class_at_ascension in ('ASSASSIN','TANK','MAGE','RANGER','COMMANDER')),
  evolved_title text,
  emblem text,
  awakened_at timestamptz,
  evolution_stage integer not null default 0 check (evolution_stage >= 0),
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.user_preferences (
  user_id uuid primary key references auth.users(id) on delete cascade,
  theme text not null default 'dark' check (theme in ('dark','light')),
  music_enabled boolean not null default true,
  music_volume numeric(4,3) not null default 0.300 check (music_volume between 0 and 1),
  music_mode text not null default 'AUTO' check (music_mode in ('AUTO','AMBIENT','INTENSE','CALM')),
  sfx_enabled boolean not null default true,
  sfx_volume numeric(4,3) not null default 0.700 check (sfx_volume between 0 and 1),
  notifications_enabled boolean not null default true,
  quest_reminders boolean not null default true,
  boss_reminders boolean not null default true,
  health_reminders boolean not null default true,
  quiet_hours_enabled boolean not null default false,
  quiet_start time,
  quiet_end time,
  timezone text not null default 'UTC',
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table public.adaptive_dimensions (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  category text not null,
  current_score numeric(6,2) not null default 50 check (current_score between 0 and 100),
  target_score numeric(6,2) not null default 70 check (target_score between 0 and 100),
  priority_weight numeric(6,3) not null default 1 check (priority_weight >= 0),
  assigned_count integer not null default 0 check (assigned_count >= 0),
  accepted_count integer not null default 0 check (accepted_count >= 0),
  completed_count integer not null default 0 check (completed_count >= 0),
  failed_count integer not null default 0 check (failed_count >= 0),
  ignored_count integer not null default 0 check (ignored_count >= 0),
  neglect_count integer not null default 0 check (neglect_count >= 0),
  last_assigned_at timestamptz,
  last_completed_at timestamptz,
  cooldown_until timestamptz,
  metadata jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now(),
  unique(user_id,category)
);

create table public.adaptive_signals (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  signal_type text not null,
  category text not null,
  severity integer not null default 1 check (severity between 1 and 5),
  title text not null,
  detail text,
  evidence jsonb not null default '{}'::jsonb,
  active boolean not null default true,
  detected_at timestamptz not null default now(),
  resolved_at timestamptz,
  metadata jsonb not null default '{}'::jsonb
);

create index user_titles_user_idx on public.user_titles(user_id);
create index adaptive_dimensions_user_idx on public.adaptive_dimensions(user_id);
create index adaptive_signals_user_active_idx on public.adaptive_signals(user_id,active);

