create table if not exists public.system_action_receipts (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references auth.users(id) on delete cascade,
  action_type text not null,
  idempotency_key text not null,
  request_hash text,
  status text not null default 'STARTED' check (status in ('STARTED','COMPLETED','FAILED')),
  result jsonb not null default '{}'::jsonb,
  error_code text,
  created_at timestamptz not null default now(),
  completed_at timestamptz,
  unique(user_id,idempotency_key)
);
create index if not exists system_action_receipts_user_time_idx on public.system_action_receipts(user_id,created_at desc);
alter table public.system_action_receipts enable row level security;
drop policy if exists system_action_receipts_select_own on public.system_action_receipts;
create policy system_action_receipts_select_own on public.system_action_receipts for select to authenticated using (user_id=(select auth.uid()));

create table if not exists public.security_events (
  id bigint generated by default as identity primary key,
  user_id uuid references auth.users(id) on delete cascade,
  event_type text not null,
  severity text not null default 'INFO' check (severity in ('INFO','WARN','BLOCK')),
  source text not null default 'SYSTEM',
  detail jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);
create index if not exists security_events_user_time_idx on public.security_events(user_id,created_at desc);
alter table public.security_events enable row level security;
drop policy if exists security_events_select_own on public.security_events;
create policy security_events_select_own on public.security_events for select to authenticated using (user_id=(select auth.uid()));

create or replace function public.system_begin_action(p_action_type text,p_idempotency_key text,p_request_hash text default null)
returns jsonb language plpgsql security definer set search_path=public,auth as $$
declare v_user uuid:=auth.uid(); v_row public.system_action_receipts;
begin
 if v_user is null then raise exception 'AUTH_REQUIRED'; end if;
 if length(trim(coalesce(p_idempotency_key,'')))<8 then raise exception 'INVALID_IDEMPOTENCY_KEY'; end if;
 insert into public.system_action_receipts(user_id,action_type,idempotency_key,request_hash)
 values(v_user,upper(trim(p_action_type)),trim(p_idempotency_key),p_request_hash)
 on conflict(user_id,idempotency_key) do nothing
 returning * into v_row;
 if found then return jsonb_build_object('accepted',true,'duplicate',false,'receipt_id',v_row.id,'status',v_row.status); end if;
 select * into v_row from public.system_action_receipts where user_id=v_user and idempotency_key=trim(p_idempotency_key);
 if v_row.request_hash is not null and p_request_hash is not null and v_row.request_hash<>p_request_hash then
   insert into public.security_events(user_id,event_type,severity,detail) values(v_user,'IDEMPOTENCY_REUSE_MISMATCH','BLOCK',jsonb_build_object('idempotency_key',p_idempotency_key,'original_action',v_row.action_type));
   raise exception 'IDEMPOTENCY_KEY_REUSED_WITH_DIFFERENT_PAYLOAD';
 end if;
 return jsonb_build_object('accepted',false,'duplicate',true,'receipt_id',v_row.id,'status',v_row.status,'result',v_row.result);
end $$;

create or replace function public.system_finish_action(p_receipt_id uuid,p_result jsonb default '{}'::jsonb,p_error_code text default null)
returns jsonb language plpgsql security definer set search_path=public,auth as $$
declare v_user uuid:=auth.uid(); v_row public.system_action_receipts;
begin
 if v_user is null then raise exception 'AUTH_REQUIRED'; end if;
 update public.system_action_receipts set status=case when p_error_code is null then 'COMPLETED' else 'FAILED' end,result=coalesce(p_result,'{}'::jsonb),error_code=p_error_code,completed_at=now()
 where id=p_receipt_id and user_id=v_user returning * into v_row;
 if not found then raise exception 'ACTION_RECEIPT_NOT_FOUND'; end if;
 return to_jsonb(v_row);
end $$;

create or replace function public.system_verify_proof_internal(p_proof_id bigint,p_status text,p_source text,p_detail jsonb default '{}'::jsonb)
returns jsonb language plpgsql security definer set search_path=public,auth as $$
declare v_row public.proof_records; v_status text:=upper(trim(p_status));
begin
 if v_status not in ('VERIFIED','REJECTED') then raise exception 'INVALID_VERIFICATION_STATUS'; end if;
 update public.proof_records set verification_status=v_status,verified_at=case when v_status='VERIFIED' then now() else null end,verification_source=coalesce(nullif(trim(p_source),''),'SYSTEM'),verification_detail=coalesce(p_detail,'{}'::jsonb)
 where id=p_proof_id returning * into v_row;
 if not found then raise exception 'PROOF_NOT_FOUND'; end if;
 return to_jsonb(v_row);
end $$;

create or replace function public.system_auto_verify_proof(p_proof_id bigint)
returns jsonb language plpgsql security definer set search_path=public,auth as $$
declare v_user uuid:=auth.uid(); v_p public.proof_records; v_ok boolean:=false; v_reason text:='MANUAL_REVIEW_REQUIRED';
begin
 if v_user is null then raise exception 'AUTH_REQUIRED'; end if;
 select * into v_p from public.proof_records where id=p_proof_id and user_id=v_user for update;
 if not found then raise exception 'PROOF_NOT_FOUND'; end if;
 if v_p.verification_status='VERIFIED' then return jsonb_build_object('verified',true,'reason','ALREADY_VERIFIED','proof',to_jsonb(v_p)); end if;
 if v_p.proof_type='GPS' and v_p.related_event_type='GPS' then
   select exists(select 1 from public.gps_sessions g where g.id::text=v_p.related_event_id and g.user_id=v_user and g.gps_verified=true) into v_ok;
   v_reason:=case when v_ok then 'GPS_SESSION_VERIFIED' else 'GPS_SESSION_NOT_VERIFIED' end;
 elsif v_p.proof_type='CHECKIN' and v_p.related_event_type='ROUTINE_CHECKIN' then
   select exists(select 1 from public.routine_checkins r where r.id::text=v_p.related_event_id and r.user_id=v_user and r.status='ON_TIME') into v_ok;
   v_reason:=case when v_ok then 'ROUTINE_CHECKIN_VERIFIED' else 'ROUTINE_CHECKIN_NOT_VERIFIED' end;
 elsif v_p.proof_type='LEARNING' and v_p.related_event_type='LEARNING_RECORD' then
   select exists(select 1 from public.learning_records l where l.id::text=v_p.related_event_id and l.user_id=v_user) into v_ok;
   v_reason:=case when v_ok then 'LEARNING_RECORD_EXISTS' else 'LEARNING_RECORD_NOT_FOUND' end;
 end if;
 if v_ok then
   update public.proof_records set verification_status='VERIFIED',verified_at=now(),verification_source='BACKEND_AUTO',verification_detail=jsonb_build_object('reason',v_reason) where id=v_p.id returning * into v_p;
 end if;
 return jsonb_build_object('verified',v_ok,'reason',v_reason,'proof',to_jsonb(v_p));
end $$;

create or replace function public.system_orchestrate_progression()
returns jsonb language plpgsql security definer set search_path=public,auth as $$
declare v_user uuid:=auth.uid(); v_ach jsonb; v_titles jsonb; v_boss jsonb; v_has_boss boolean; v_boss_hp integer; v_open int;
begin
 if v_user is null then raise exception 'AUTH_REQUIRED'; end if;
 v_ach:=public.system_evaluate_achievements();
 v_titles:=public.system_evaluate_titles();
 select exists(select 1 from public.boss_quests where user_id=v_user and status='ACTIVE'),
        coalesce((select hp from public.boss_quests where user_id=v_user and status='ACTIVE' order by created_at desc limit 1),1)
 into v_has_boss,v_boss_hp;
 if v_has_boss and v_boss_hp<=0 then
   select count(*) into v_open from public.boss_quest_objectives o join public.boss_quests b on b.id=o.boss_quest_id where b.user_id=v_user and b.status='ACTIVE' and o.is_complete=false;
   if v_open=0 then
     begin v_boss:=public.system_resolve_active_boss(); exception when others then v_boss:=jsonb_build_object('resolved',false,'reason',sqlerrm); end;
   else v_boss:=jsonb_build_object('resolved',false,'reason','OBJECTIVES_REMAIN'); end if;
 else v_boss:=jsonb_build_object('resolved',false,'reason',case when v_has_boss then 'BOSS_HP_REMAINS' else 'NO_ACTIVE_BOSS' end); end if;
 return jsonb_build_object('achievements',v_ach,'titles',v_titles,'boss',v_boss);
end $$;

