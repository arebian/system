create table public.performance_logs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  metric text not null,
  value numeric not null,
  unit text,
  note text,
  source text not null default 'MANUAL',
  metadata jsonb not null default '{}'::jsonb,
  recorded_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

create index performance_logs_user_id_recorded_at_idx
  on public.performance_logs(user_id, recorded_at desc);

alter table public.performance_logs enable row level security;

grant select, insert, update, delete on public.performance_logs to authenticated;

grant all on public.performance_logs to service_role;

create policy "performance_logs_select_own"
  on public.performance_logs
  for select
  to authenticated
  using ((select auth.uid()) = user_id);

create policy "performance_logs_insert_own"
  on public.performance_logs
  for insert
  to authenticated
  with check ((select auth.uid()) = user_id);

create policy "performance_logs_update_own"
  on public.performance_logs
  for update
  to authenticated
  using ((select auth.uid()) = user_id)
  with check ((select auth.uid()) = user_id);

create policy "performance_logs_delete_own"
  on public.performance_logs
  for delete
  to authenticated
  using ((select auth.uid()) = user_id);

create table public.wealth_logs (
  id bigint generated by default as identity primary key,
  user_id uuid not null references auth.users(id) on delete cascade,
  type text not null check (type in ('SAVINGS','INCOME','DEBT CLEARED','INVESTMENT','CHAMA','OTHER')),
  amount numeric(14,2) not null check (amount >= 0),
  currency text not null default 'KES',
  note text,
  source text not null default 'MANUAL',
  metadata jsonb not null default '{}'::jsonb,
