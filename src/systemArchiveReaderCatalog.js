  "PROJECT GUTENBERG • PUBLIC-DOMAIN SOURCE";

function projectGutenbergEdition(
  ebookNumber,
  overrides = {},
) {
  const id = String(ebookNumber);

  return Object.freeze({
    ebookNumber: id,
    readerMode: "SYSTEM_NATIVE_TEXT",
    textUrl:
      "https://www.gutenberg.org/cache/epub/" +
      id +
      "/pg" + id + ".txt",
    sourceUrl:
      "https://www.gutenberg.org/ebooks/" +
      id,
    sourceLabel: PROJECT_GUTENBERG_SOURCE_LABEL,
    editionLabel: "THE SYSTEM NATIVE PUBLIC-DOMAIN READER",
    pageCount: null,
    ...overrides,
  });
}

